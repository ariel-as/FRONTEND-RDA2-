import assert from 'node:assert/strict';
const session=new Map();
globalThis.sessionStorage={getItem:(k)=>session.get(k)??null,setItem:(k,v)=>session.set(k,String(v)),removeItem:(k)=>session.delete(k)};
globalThis.window={dispatchEvent:()=>{}};
let urlRecibida='';
globalThis.fetch=async(url)=>{urlRecibida=String(url);return new Response(JSON.stringify({data:[{id:'PF1'}]}),{status:200,headers:{'content-type':'application/json'}});};
const {api}=await import('../frontend/models/api.model.js');
const respuesta=await api.get('/productos');
assert.equal(respuesta.data[0].id,'PF1');
assert.match(urlRecibida,/localhost:5050\/api\/v1\/productos$/);
globalThis.fetch=async()=>{throw new TypeError('network');};
await assert.rejects(api.get('/productos'),(error)=>error.status===0&&/conectar/.test(error.mensaje));
console.log('Repositorio HTTP: URL centralizada, respuesta JSON y error de red normalizado.');
