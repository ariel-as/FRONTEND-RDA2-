import assert from 'node:assert/strict';
const local=new Map();
globalThis.localStorage={getItem:(k)=>local.get(k)??null,setItem:(k,v)=>local.set(k,String(v)),removeItem:(k)=>local.delete(k)};
globalThis.CustomEvent=class { constructor(type,init){this.type=type;this.detail=init?.detail;} };
globalThis.window={location:{protocol:'http:'},dispatchEvent:()=>{}};
const { carrito, formatearPrecio }=await import('../frontend/models/carrito.model.js');
carrito.vaciar();
carrito.agregar({id:'PF1',nombre:'Producto',precio:12.5,stock:3});
carrito.agregar({id:'PF1',nombre:'Producto',precio:12.5,stock:3},10);
assert.equal(carrito.obtener()[0].cantidad,3,'la cantidad debe respetar el stock disponible');
carrito.agregar({id:'MI1',nombre:'Plan',precio:35,tipo:'plan'},2);
assert.equal(carrito.obtener().find((item)=>item.id==='MI1').cantidad,1,'un plan no se duplica');
assert.equal(carrito.total(),72.5);
assert.equal(formatearPrecio(72.5),'$72.50');
console.log('Lógica: stock, límite de plan, subtotal y formato monetario correctos.');
