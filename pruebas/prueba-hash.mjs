import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const main=readFileSync('frontend/controllers/main.controller.js','utf8');
const inicio=readFileSync('frontend/controllers/inicio.controller.js','utf8');
const comunes=readFileSync('frontend/controllers/comunes.controller.js','utf8');
const css=readFileSync('frontend/assets/css/styles.css','utf8');
assert.match(main,/history\.scrollRestoration\s*=\s*['"]manual['"]/);
assert.match(main,/if\s*\(location\.hash\)[\s\S]*pf-posicion-pendiente/);
assert.match(inicio,/alinearConHash\(\)/);
assert.match(comunes,/prefers-reduced-motion: reduce/);
assert.match(comunes,/behavior: reducido\(\) \|\| lejos \? 'instant' : 'smooth'/);
assert.match(css,/html\.pf-posicion-pendiente/);
assert.match(css,/@media\s*\(prefers-reduced-motion:\s*reduce\)/);
console.log('Hash: restauración manual, realineación dinámica y movimiento reducido siguen conectados.');
